import ExcelJS from 'exceljs';
import type { DtrRecord } from './dtr.types.js';
import { summarizeDtr, localWallTime } from './dtr.calculator.js';

export function safeCell(value: string): string {
  let start = value.trimStart();
  while (start.length && start.charCodeAt(0) < 32)
    start = start.slice(1).trimStart();
  return start.length && '=+@-'.includes(start[0]) ? `'${value}` : value;
}
const headers = [
  'Name',
  'Date',
  'ACTUAL IN',
  'ACTUAL OUT',
  'SCHEDULE IN',
  'SCHEDULE OUT',
  'POTENTIAL OT (min)',
  'LATES (min)',
  'UNDERTIME (min)',
  'ABSENT (days)',
  'RESTDAY/SPECIAL HOLIDAY',
  'HOLIDAY',
  'REMARKS',
  'APPROVED OT (min)',
  'STATUS',
  'EXCEPTIONS',
  'REVISION',
  'LEAVE CODE',
  'PAID LEAVE (days)',
  'UNPAID LEAVE (days)',
  'APPROVED OB (min)',
  'OFFICE EVIDENCE (min)',
  'TOTAL CREDITED WORK (min)',
  'ATTESTED OFFICE (min)',
];
function rowValues(row: DtrRecord): (string | number)[] {
  const c = row.data.calculation;
  const time = (value: string | null, missing: string) =>
    c.restDay && !value
      ? 'RD'
      : value
        ? localWallTime(new Date(value), c.timeZone).slice(11)
        : missing;
  const ready = (value: number) => (c.payrollReady ? value : '');
  return [
    safeCell(row.employeeName),
    row.workDate,
    time(c.actualIn, 'No time in'),
    time(c.actualOut, 'No time out'),
    c.restDay ? 'RD' : (c.schedule?.shiftStart ?? ''),
    c.restDay ? 'RD' : (c.schedule?.shiftEnd ?? ''),
    ready(c.potentialOtMinutes),
    ready(c.lateMinutes),
    ready(c.undertimeMinutes),
    ready(c.absent),
    c.restDay ? 'RD' : c.holiday === 'Special Non-working Day' ? c.holiday : '',
    c.holiday ?? '',
    safeCell(c.remarks),
    ready(c.approvedOtMinutes),
    c.statuses.join(', '),
    c.exceptions.join('; '),
    row.data.revision,
    (c.leaveTypes ?? []).join(", "),
    c.paidLeaveUnits ?? 0,
    Math.max(0,c.leaveUnits-(c.paidLeaveUnits??0)),
    c.obCreditedMinutes ?? 0,
    c.actualWorkedMinutes ?? c.workedMinutes,
    c.workedMinutes,
    c.attestedOfficeMinutes ?? 0,
  ];
}
export async function exportDtr(
  rows: DtrRecord[],
  options: {
    branchName: string;
    from: string;
    to: string;
    actor: string;
    format: 'csv' | 'xlsx';
    report?: 'DTR' | 'SUMMARY';
  },
): Promise<Buffer> {
  const ordered = [...rows].sort(
    (a, b) =>
      a.employeeName.localeCompare(b.employeeName) ||
      a.employeeId.localeCompare(b.employeeId) ||
      a.workDate.localeCompare(b.workDate),
  );
  const groups = new Map<string, DtrRecord[]>();
  for (const row of ordered)
    groups.set(row.employeeId, [...(groups.get(row.employeeId) ?? []), row]);
  const data: (string | number)[][] = [];
  for (const group of groups.values()) {
    data.push(...group.map(rowValues));
    const total = summarizeDtr(group);
    data.push([
      `TOTAL ${safeCell(group[0].employeeName)}`,
      '',
      '',
      '',
      '',
      '',
      total.potentialOtMinutes,
      total.lateMinutes,
      total.undertimeMinutes,
      total.absenceDays,
      '',
      '',
      `${total.excludedDays} unresolved days excluded`,
      total.approvedOtMinutes,
      '',
      '',
      '',
    ]);
  }
  if (options.format === 'csv') {
    const quote = (v: string | number) =>
      `"${String(typeof v === 'string' ? safeCell(v) : v).replace(/"/g, '""')}"`;
    const summaryRows = [
      [
        'Employee',
        'Employee days',
        'Late minutes',
        'Undertime minutes',
        'Potential OT minutes',
        'Approved OT minutes',
        'Absence days',
        'Excluded days',
      ],
      ...[...groups.values(), ordered].map((group) => {
        const s = summarizeDtr(group);
        return [
          group === ordered ? 'ALL EMPLOYEES' : group[0].employeeName,
          s.employeeDays,
          s.lateMinutes,
          s.undertimeMinutes,
          s.potentialOtMinutes,
          s.approvedOtMinutes,
          s.absenceDays,
          s.excludedDays,
        ];
      }),
    ];
    return Buffer.from(
      '\ufeff' +
        (options.report === 'SUMMARY' ? summaryRows : [headers, ...data])
          .map((r) => r.map(quote).join(','))
          .join('\r\n'),
      'utf8',
    );
  }
  const book = new ExcelJS.Workbook();
  book.creator = options.actor;
  book.created = new Date();
  const summary = book.addWorksheet('Summary');
  summary.addRow([
    'ATTENDANCE',
    safeCell(options.branchName),
    `${options.from} to ${options.to}`,
  ]);
  summary.addRow([
    'Generated at',
    new Date().toISOString(),
    'Generated by',
    safeCell(options.actor),
  ]);
  summary.addRow([
    'Units',
    'Integer minutes; absence in days. Unresolved rows excluded from totals.',
  ]);
  const summaryHeaders = [
    'Employee',
    'Employee days',
    'Present days',
    'Absence days',
    'Late occurrences',
    'Late minutes',
    'Undertime minutes',
    'Potential OT minutes',
    'Approved OT minutes',
    'Excluded days',
  ];
  summary.addRow(summaryHeaders);
  for (const group of [...groups.values(), ordered]) {
    const s = summarizeDtr(group);
    summary.addRow([
      group === ordered ? 'ALL EMPLOYEES' : safeCell(group[0].employeeName),
      s.employeeDays,
      s.presentDays,
      s.absenceDays,
      s.lateOccurrences,
      s.lateMinutes,
      s.undertimeMinutes,
      s.potentialOtMinutes,
      s.approvedOtMinutes,
      s.excludedDays,
    ]);
  }
  const dtr = book.addWorksheet('Employee DTR', {
    views: [{ state: 'frozen', ySplit: 2, xSplit: 2 }],
  });
  dtr.addRow([
    'ATTENDANCE',
    safeCell(options.branchName),
    `${options.from} to ${options.to}`,
  ]);
  dtr.addRow(headers);
  for (const values of data) {
    const row = dtr.addRow(values);
    if (String(values[0]).startsWith('TOTAL ')) {
      row.font = { bold: true };
      row.fill = {
        type: 'pattern',
        pattern: 'solid',
        fgColor: { argb: 'FFDCE6F1' },
      };
    } else {
      row.getCell(2).value = new Date(`${values[1]}T00:00:00Z`);
      row.getCell(2).numFmt = 'dddd, mmmm d, yyyy';
      for (const column of [3, 4, 5, 6])
        if (/^\d{2}:\d{2}$/.test(String(values[column - 1]))) {
          const [h, m] = String(values[column - 1])
            .split(':')
            .map(Number);
          row.getCell(column).value = (h * 60 + m) / 1440;
          row.getCell(column).numFmt = 'hh:mm';
        }
      if (values[15]) row.font = { color: { argb: 'FFB42318' } };
    }
  }
  dtr.autoFilter = { from: 'A2', to: `X${Math.max(2, dtr.rowCount)}` };
  const exceptions = book.addWorksheet('Exceptions');
  exceptions.addRow(headers);
  ordered
    .filter((r) => !r.data.calculation.payrollReady)
    .forEach((r) => exceptions.addRow(rowValues(r)));
  for (const sheet of book.worksheets) {
    sheet.columns.forEach((column, i) => {
      column.width = i === 0 ? 28 : i === 1 ? 34 : 22;
    });
    const headerRow = sheet === summary ? 4 : sheet === dtr ? 2 : 1;
    sheet.getRow(headerRow).font = { bold: true, color: { argb: 'FFFFFFFF' } };
    sheet.getRow(headerRow).fill = {
      type: 'pattern',
      pattern: 'solid',
      fgColor: { argb: 'FF343A40' },
    };
    sheet.pageSetup = {
      orientation: 'landscape',
      fitToPage: true,
      fitToWidth: 1,
      fitToHeight: 0,
    };
  }
  return Buffer.from(await book.xlsx.writeBuffer());
}
